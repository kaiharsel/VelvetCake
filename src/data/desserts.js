export const getDessert = (slug) => desserts.find((d) => d.slug === slug)

export const getRelated = (slug, count = 3) => {
  const current = getDessert(slug)
  if (!current) return desserts.slice(0, count)
  const sameCat = desserts.filter(
    (d) => d.slug !== slug && d.category === current.category,
  )
  const others = desserts.filter(
    (d) => d.slug !== slug && d.category !== current.category,
  )
  return [...sameCat, ...others].slice(0, count)
}

export const featuredDesserts = desserts.filter((d) => d.featured)
